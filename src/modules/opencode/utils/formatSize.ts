/**
 * Человекочитаемый размер файла для списка вложений.
 *
 * Единицы — русские («Б/КБ/МБ»); английская локаль использует те же
 * сокращения, потому что ключ размера формируется как суффикс к числу и не
 * переводится через i18n (число и единица должны читаться как одно целое).
 * Существующий `formatirovatBayty` из модуля runner намеренно не переиспользуется:
 * он выдаёт двоичные единицы `B/KiB/MiB` для метрик ресурсов сервера.
 */
export function formatSize(bytes: number): string {
    if (!Number.isFinite(bytes) || bytes <= 0) {
        return "0 Б";
    }

    if (bytes < 1024) {
        return `${Math.round(bytes)} Б`;
    }

    if (bytes < 1024 * 1024) {
        return `${(bytes / 1024).toFixed(1)} КБ`;
    }

    return `${(bytes / (1024 * 1024)).toFixed(1)} МБ`;
}
